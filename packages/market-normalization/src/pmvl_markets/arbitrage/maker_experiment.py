#: Markout horizons, in seconds. Fixed before any forward data was recorded.
MARKOUT_HORIZONS = (30, 60, 300)

TICK = Decimal("0.01")


class FillEstimator(StrEnum):
    #: Volume printed strictly past the quote. Proves the level was cleared.
    TRADED_THROUGH = "TRADED_THROUGH"
    #: At-or-through volume minus the size already resting at the price.
    QUEUE_MODEL = "QUEUE_MODEL"
    #: Any print at the price counts as a full fill. Inadmissible; measured for contrast.
    TOUCHED = "TOUCHED"


ADMISSIBLE_ESTIMATORS = (FillEstimator.TRADED_THROUGH, FillEstimator.QUEUE_MODEL)


@dataclass(frozen=True)
class QuotePolicy:
    """The rule that decides where to quote. Declared, not discovered.

    ``improve_ticks`` of 0 joins the best bid; 1 steps in front of it. Stepping in
    front buys queue priority with a worse price, and which of those dominates is
    precisely the thing being measured, so it is a parameter rather than a choice
    made after looking.
    """

    side: Side = Side.YES
    improve_ticks: int = 0
    size: Decimal = Decimal("50")
    lifetime_seconds: int = 60
    #: Quotes are only placed when the market is two-sided and the spread is at least
    #: this wide; quoting into a one-tick spread is a different strategy.
    min_spread: Decimal = Decimal("0.02")
    #: Kalshi charges makers only on series configured for it. Zero is the common
    #: case and is stated rather than assumed silently.
    maker_fee_rate: Decimal = ZERO
    #: Charged on the unwind, which is a taker order. The published multiplier-1
    #: schedule; a series with a higher multiplier makes the strategy worse, never
    #: better, so this is the optimistic end and is stated as a parameter.
    taker_fee_rate: Decimal = KALSHI_TAKER_RATE
    #: Gap between seeing the book and the order resting on it. Prints inside this
    #: window happened while the order was still in flight and cannot have filled it.
    #: Counting them is the easy way to manufacture a fill rate: the default is the
    #: observed batch round trip, which is a *lower* bound on real placement latency.
    placement_latency_ms: int = 300
    #: The venue's minimum price increment. Kalshi ticks at a cent and Polymarket at a
    #: tenth of one, so "improve by one tick" means ten times as much on one venue as
    #: the other. It belongs to the declared policy rather than to a module constant,
    #: because a constant changed at runtime is a setting nobody can see in the report.
    tick: Decimal = TICK
    name: str = "join-the-bid"

    def as_dict(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "side": self.side.value,
            "improve_ticks": self.improve_ticks,
            "size": str(self.size),
            "lifetime_seconds": self.lifetime_seconds,
            "min_spread": str(self.min_spread),
            "maker_fee_rate": str(self.maker_fee_rate),
            "taker_fee_rate_on_unwind": str(self.taker_fee_rate),
            "placement_latency_ms": self.placement_latency_ms,
            "tick": str(self.tick),
        }


@dataclass(frozen=True)
class MakerQuote:
    """One order that would have been placed, with the queue it would have joined."""

    market: str
    event_ticker: str
    side: Side
    price: Decimal
    size: Decimal
    placed_at: datetime
    expires_at: datetime
    queue_ahead: Decimal
    spread_at_placement: Decimal
    snapshot_sequence: int

    @property
    def yes_price(self) -> Decimal:
        """The quote expressed in the coordinate the tape uses.

        Every Kalshi print is stamped with a YES price regardless of which side the
        aggressor took, so a NO bid at 0.62 and a YES ask at 0.38 are the same line
        on the tape. Comparing a NO quote against ``yes_price_dollars`` without this
        conversion silently matches the wrong prints.
        """
        return self.price if self.side == Side.YES else ONE - self.price

    def is_relevant(self, trade: TradeRecord) -> bool:
        """A print can only fill this quote if the aggressor took the other side."""
        if self.side == Side.YES:
            return trade.taker_side == "no"
        return trade.taker_side == "yes"

    def at_level(self, trade: TradeRecord) -> bool:
        return trade.yes_price == self.yes_price

    def through(self, trade: TradeRecord) -> bool:
        """Printed past the quote, which can only happen once the level is gone."""
        if self.side == Side.YES:
            return trade.yes_price < self.yes_price
        return trade.yes_price > self.yes_price


@dataclass(frozen=True)
class QuoteOutcome:
    """What happened to one quote under each estimator."""

    quote: MakerQuote
    filled_size: dict[FillEstimator, Decimal]
    first_fill_at: datetime | None
    relevant_volume_at_level: Decimal
    relevant_volume_through: Decimal
    #: horizon seconds -> mark-to-market PnL per the recorded book, net of the maker fee
    markout: dict[int, Decimal | None]
    #: What flattening the position as a taker would have netted, fees included.
    liquidation_pnl: Decimal | None
    hedge_cost: Decimal | None
    hedge_available: bool

    def filled(self, estimator: FillEstimator) -> bool:
        return self.filled_size.get(estimator, ZERO) > 0

    def pnl(self, estimator: FillEstimator, *, horizon: int) -> Decimal:
        """Unconditional: a quote that did not fill under this estimator earns zero."""
        size = self.filled_size.get(estimator, ZERO)
        if size <= 0:
            return ZERO
        per_contract = self.markout.get(horizon)
        if per_contract is None:
            return ZERO
        return quantize_usd(per_contract * size)


# ------------------------------------------------------------------ generation
def generate_quotes(
    snapshots: Sequence[EventSnapshot], policy: QuotePolicy
) -> list[MakerQuote]:
    """Every quote the policy would have placed, with no overlap on a market.

    Non-overlapping by construction: the next quote on a market is only placed once
    the previous one has expired. Overlapping quotes on the same book are the same
    bet counted twice - they share the trades that fill them and the move that
    follows - and pooling them would shrink the confidence interval around a number
    that has not become any better known.
    """
    quotes: list[MakerQuote] = []
    busy_until: dict[str, datetime] = {}

    for snapshot in sorted(snapshots, key=lambda s: s.response_received_at):
        if not snapshot.is_synchronized:
            continue
        observed = snapshot.response_received_at
        for market, book in sorted(snapshot.books.items()):
            if busy_until.get(market) and observed < busy_until[market]:
                continue
            quote = _quote_from_book(
                market, snapshot.event_ticker, book, policy, observed, snapshot.sequence
            )
            if quote is None:
                continue
            quotes.append(quote)
            busy_until[market] = quote.expires_at
    return quotes


def _quote_from_book(
    market: str,
    event_ticker: str,
    book: OrderBook,
    policy: QuotePolicy,
    observed: datetime,
    sequence: int,
) -> MakerQuote | None:
    best_bid = book.best_bid(policy.side)
    best_ask = book.best_ask(policy.side)
    if best_bid is None or best_ask is None or best_bid <= 0:
        return None
    spread = best_ask - best_bid
    if spread < policy.min_spread:
        return None

    price = best_bid + policy.tick * policy.improve_ticks
    if price >= best_ask or price <= ZERO or price >= ONE:
        return None

    #: Joining the touch means queueing behind the size already there. Improving the
    #: price means an empty queue - nobody is resting at a price that did not exist.
    queue_ahead = ZERO
    if policy.improve_ticks == 0:
        for level in book.bids(policy.side):
            if level.price == price:
                queue_ahead = level.size
                break

    return MakerQuote(
        market=market,
        event_ticker=event_ticker,
        side=policy.side,
        price=price,
        size=policy.size,
        placed_at=observed,
        expires_at=observed + timedelta(seconds=policy.lifetime_seconds),
        queue_ahead=queue_ahead,
        spread_at_placement=spread,
        snapshot_sequence=sequence,
    )


# ------------------------------------------------------------------ evaluation
class ReplayIndex:
    """Trades and books grouped by market, once, instead of once per quote.

    Without it the replay is quadratic: every quote rescans every print and every
    snapshot, and a ninety-minute recording of three hundred legs is tens of
    thousands of quotes against tens of thousands of prints. The index changes no
    result - it is the same data in a different order - but it is what makes running
    the experiment over the whole recording, rather than a sample of it, practical.
    Sampling the recording would be a selection, and selections are what this whole
    phase exists to avoid.
    """

    def __init__(
        self, trades: Sequence[TradeRecord], snapshots: Sequence[EventSnapshot]
    ) -> None:
        self.trades: dict[str, list[TradeRecord]] = {}
        for trade in trades:
            self.trades.setdefault(trade.platform_market_id, []).append(trade)
        for rows in self.trades.values():
            rows.sort(key=lambda t: t.traded_at)

        self.books: dict[str, list[tuple[datetime, OrderBook]]] = {}
        for snapshot in sorted(snapshots, key=lambda s: s.response_received_at):
            if not snapshot.is_synchronized:
                continue
            for market, book in snapshot.books.items():
                self.books.setdefault(market, []).append(
                    (snapshot.response_received_at, book)
                )

    def trades_for(self, market: str) -> list[TradeRecord]:
        return self.trades.get(market, [])

    def book_at(self, market: str, when: datetime) -> OrderBook | None:
        """The first recorded book at or after ``when``. Never one from before it."""
        rows = self.books.get(market)
        if not rows:
            return None
        lo, hi = 0, len(rows)
        while lo < hi:
            mid = (lo + hi) // 2
            if rows[mid][0] < when:
                lo = mid + 1
            else:
                hi = mid
        return rows[lo][1] if lo < len(rows) else None


def evaluate_quote(
    quote: MakerQuote,
    trades: Sequence[TradeRecord],
    snapshots: Sequence[EventSnapshot],
    *,
    policy: QuotePolicy,
    hedge: tuple[str, Side] | None = None,
    index: "ReplayIndex | None" = None,
) -> QuoteOutcome:
    """Fill, markout and hedge cost for one quote, from the tape and the recorded book."""
    index = index or ReplayIndex(trades, snapshots)
    live_from = quote.placed_at + timedelta(milliseconds=policy.placement_latency_ms)
    window = [
        t
        for t in index.trades_for(quote.market)
        if live_from <= t.traded_at <= quote.expires_at
        and quote.is_relevant(t)
        and not t.is_block_trade
    ]

    at_level = sum((t.size for t in window if quote.at_level(t)), ZERO)
    through = sum((t.size for t in window if quote.through(t)), ZERO)
    touched_any = any(quote.at_level(t) or quote.through(t) for t in window)

    #: Every contract printed *past* the quote is one that, had the quote been there,
    #: would have hit it first - so through-volume is a fill, bounded by the quote's
    #: own size. It is not evidence of a fill for the *whole* size: a taker who sold
    #: 24 contracts through a 3-deep queue tells you 21 would have been yours, not
    #: 50. Reading "traded through" as "filled in full" overstates fills by whatever
    #: the quote asked for beyond what actually traded, which on a thin book is most
    #: of it.
    through_size = min(through, quote.size)
    #: FIFO with a static queue. The max keeps the two estimators ordered when the
    #: tape and the book disagree - volume cannot print past a queue that is still
    #: standing, so if it did, the recorded queue was already stale.
    queue_size = min(
        quote.size, max(through_size, max(ZERO, at_level + through - quote.queue_ahead))
    )
    traded_through_size = through_size
    touched_size = quote.size if touched_any else ZERO

    filled_size = {
        FillEstimator.TRADED_THROUGH: traded_through_size,
        FillEstimator.QUEUE_MODEL: queue_size,
        FillEstimator.TOUCHED: touched_size,
    }

    first_fill_at = _first_fill_time(quote, window)

    markout: dict[int, Decimal | None] = {}
    reference = first_fill_at or quote.expires_at
    for horizon in MARKOUT_HORIZONS:
        markout[horizon] = _markout_per_contract(
            quote, index, reference, horizon, policy
        )

    liquidation = _liquidation_per_contract(quote, index, reference, policy)
    #: The natural hedge for a maker fill is the *other side of the same market*:
    #: holding both pays exactly $1 whatever settles, so the pair is closed the
    #: moment it is on. Defaulting to it means hedge cost is always measured rather
    #: than only measured when a partner leg was configured - and it is the cheapest
    #: hedge available, so a strategy that fails against it fails against any.
    target = hedge or (
        quote.market, Side.NO if quote.side == Side.YES else Side.YES
    )
    hedge_cost, hedge_available = _hedge(
        quote, index, reference, target, taker_rate=policy.taker_fee_rate
    )

    return QuoteOutcome(
        quote=quote,
        filled_size=filled_size,
        first_fill_at=first_fill_at,
        relevant_volume_at_level=at_level,
        relevant_volume_through=through,
        markout=markout,
        liquidation_pnl=liquidation,
        hedge_cost=hedge_cost,
        hedge_available=hedge_available,
    )


def _first_fill_time(
    quote: MakerQuote, window: Sequence[TradeRecord]
) -> datetime | None:
    """When the queue ahead is cleared, which is the earliest the quote can have traded."""
    cumulative = ZERO
    for trade in window:
        if quote.through(trade):
            return trade.traded_at
        if quote.at_level(trade):
            cumulative += trade.size
            if cumulative > quote.queue_ahead:
                return trade.traded_at
    return None


def _markout_per_contract(
    quote: MakerQuote,
    index: ReplayIndex,
    reference: datetime,
    horizon: int,
    policy: QuotePolicy,
) -> Decimal | None:
    """Mid-price markout per contract, net of any maker fee.

    Uses the *mid* rather than the bid deliberately: the bid understates the position
    by a full spread and would make every maker fill look bad regardless of whether
    the market moved. The liquidation number below is the one that charges the spread.
    """
    book = index.book_at(quote.market, reference + timedelta(seconds=horizon))
    if book is None:
        return None
    bid = book.best_bid(quote.side)
    ask = book.best_ask(quote.side)
    if bid is None or ask is None:
        return None
    mid = (bid + ask) / 2
    fee = (
        kalshi_maker_fee(quote.size, quote.price, rate=policy.maker_fee_rate)
        if policy.maker_fee_rate > 0
        else ZERO
    )
    return quantize_usd(mid - quote.price - (fee / quote.size if quote.size else ZERO))


def _liquidation_per_contract(
    quote: MakerQuote,
    index: ReplayIndex,
    reference: datetime,
    policy: QuotePolicy,
) -> Decimal | None:
    """What flattening into the book at the last horizon would net, per contract.

    Selling the position means buying the opposite side as a taker, which pays the
    spread and a taker fee. This is the number a maker actually realises if they do
    not intend to hold to settlement.
    """
    book = index.book_at(
        quote.market, reference + timedelta(seconds=MARKOUT_HORIZONS[-1])
    )
    if book is None:
        return None
    other = Side.NO if quote.side == Side.YES else Side.YES
    unwind_ask = book.best_ask(other)
    if unwind_ask is None:
        return None
    #: Buying the other side flattens the pair for $1 of settlement value.
    proceeds = ONE - unwind_ask
    fee = taker_fee(Platform.KALSHI, quote.size, unwind_ask, rate=policy.taker_fee_rate)
    maker_fee = (
        kalshi_maker_fee(quote.size, quote.price, rate=policy.maker_fee_rate)
        if policy.maker_fee_rate > 0
        else ZERO
    )
    per_contract_fees = (fee + maker_fee) / quote.size if quote.size else ZERO
    return quantize_usd(proceeds - quote.price - per_contract_fees)


def _hedge(
    quote: MakerQuote,
    index: ReplayIndex,
    reference: datetime,
    hedge: tuple[str, Side] | None,
    *,
    taker_rate: Decimal = KALSHI_TAKER_RATE,
) -> tuple[Decimal | None, bool]:
    """Taker cost of the second leg, from the book standing when the fill happened."""
    if hedge is None:
        return None, False
    market, side = hedge
    book = index.book_at(market, reference)
    if book is None:
        return None, False
    ask = book.best_ask(side)
    if ask is None:
        return None, False
    fee = taker_fee(Platform.KALSHI, quote.size, ask, rate=taker_rate)
    return quantize_usd(ask + (fee / quote.size if quote.size else ZERO)), True


# --------------------------------------------------------------------- report
@dataclass
class MakerExperimentReport:
    policy: QuotePolicy
    strategy_version: str
    quotes_placed: int = 0
    #: Quotes dropped because the tape was not known complete through their window.
    #: Counted, never silently discarded - a large number here means the recording
    #: ended before its prints were indexed, not that the market was quiet.
    quotes_excluded_tape_incomplete: int = 0
    markets: int = 0
    event_days: int = 0
    #: Calendar dates covered. Eight events recorded in one afternoon are eight
    #: event-days and *one* session: they share the macro conditions, the exchange's
    #: state and whatever the market makers were doing that day. Reporting only the
    #: event-day count would let a single session read as eight independent draws.
    distinct_dates: int = 0
    outcomes: list[QuoteOutcome] = field(default_factory=list)

    def fills(self, estimator: FillEstimator) -> int:
        return sum(1 for o in self.outcomes if o.filled(estimator))

    def fill_rate(self, estimator: FillEstimator) -> Decimal:
        if not self.quotes_placed:
            return ZERO
        return Decimal(self.fills(estimator)) / Decimal(self.quotes_placed)

    def completion_rate(self, estimator: FillEstimator) -> Decimal:
        """Fraction of filled quotes that filled for their whole declared size."""
        filled = [o for o in self.outcomes if o.filled(estimator)]
        if not filled:
            return ZERO
        whole = sum(1 for o in filled if o.filled_size[estimator] >= o.quote.size)
        return Decimal(whole) / Decimal(len(filled))

    def unconditional_pnl(self, estimator: FillEstimator, *, horizon: int) -> Decimal:
        return quantize_usd(
            sum((o.pnl(estimator, horizon=horizon) for o in self.outcomes), ZERO)
        )

    def expectancy_per_quote(
        self, estimator: FillEstimator, *, horizon: int
    ) -> Decimal:
        if not self.quotes_placed:
            return ZERO
        return quantize_usd(
            self.unconditional_pnl(estimator, horizon=horizon)
            / Decimal(self.quotes_placed)
        )

    def mean_markout_given_fill(
        self, estimator: FillEstimator, *, horizon: int
    ) -> Decimal | None:
        values = [
            o.markout[horizon]
            for o in self.outcomes
            if o.filled(estimator) and o.markout.get(horizon) is not None
        ]
        if not values:
            return None
        return quantize_usd(sum(values, ZERO) / Decimal(len(values)))

    def mean_hedge_cost_given_fill(self, estimator: FillEstimator) -> Decimal | None:
        values = [
            o.hedge_cost
            for o in self.outcomes
            if o.filled(estimator) and o.hedge_cost is not None
        ]
        if not values:
            return None
        return quantize_usd(sum(values, ZERO) / Decimal(len(values)))

    def hedge_availability(self, estimator: FillEstimator) -> Decimal:
        """Fraction of fills for which a hedge was quoted at all when it was needed."""
        filled = [o for o in self.outcomes if o.filled(estimator)]
        if not filled:
            return ZERO
        return Decimal(sum(1 for o in filled if o.hedge_available)) / Decimal(len(filled))

    def hedged_pair_pnl(self, estimator: FillEstimator) -> Decimal | None:
        """Mean per-contract PnL of buying the fill and immediately hedging it.

        The pair settles for exactly $1, so this is ``1 - fill price - hedge cost``.
        It is the number a market maker who refuses to carry inventory would earn,
        and it needs no view on where the price goes next.
        """
        values = [
            ONE - o.quote.price - o.hedge_cost
            for o in self.outcomes
            if o.filled(estimator) and o.hedge_cost is not None
        ]
        if not values:
            return None
        return quantize_usd(sum(values, ZERO) / Decimal(len(values)))

    def cluster_bootstrap_ci(
        self, estimator: FillEstimator, *, horizon: int, iterations: int = 2000,
        seed: int = 20260918,
    ) -> tuple[Decimal, Decimal] | None:
        """95% interval for expectancy per quote, resampling **whole markets**.

        Quotes on one market over one session are not independent draws: they share a
        book, a spread regime and whatever moved the price that afternoon. Resampling
        individual quotes would treat a few hundred correlated observations as a few
        hundred independent ones and return an interval several times too narrow. The
        unit resampled here is the market, which is the coarsest grouping the
        recording supports.
        """
        import random

        clusters: dict[tuple[str, str], list[Decimal]] = {}
        for outcome in self.outcomes:
            key = (
                outcome.quote.market,
                outcome.quote.placed_at.date().isoformat(),
            )
            clusters.setdefault(key, []).append(outcome.pnl(estimator, horizon=horizon))
        groups = list(clusters.values())
        if len(groups) < 2:
            return None

        rng = random.Random(seed)
        means: list[Decimal] = []
        for _ in range(iterations):
            drawn: list[Decimal] = []
            for _ in range(len(groups)):
                drawn.extend(rng.choice(groups))
            if drawn:
                means.append(sum(drawn, ZERO) / Decimal(len(drawn)))
        if not means:
            return None
        means.sort()
        low = means[int(0.025 * (len(means) - 1))]
        high = means[int(0.975 * (len(means) - 1))]
        return quantize_usd(low), quantize_usd(high)

    def mean_liquidation_given_fill(self, estimator: FillEstimator) -> Decimal | None:
        values = [
            o.liquidation_pnl
            for o in self.outcomes
            if o.filled(estimator) and o.liquidation_pnl is not None
        ]
        if not values:
            return None
        return quantize_usd(sum(values, ZERO) / Decimal(len(values)))

    def as_dict(self) -> dict[str, Any]:
        body: dict[str, Any] = {
            "recording_version": self.strategy_version,
            "analysis_version": ANALYSIS_VERSION,
            "policy": self.policy.as_dict(),
            "quotes_placed": self.quotes_placed,
            "quotes_excluded_tape_incomplete": self.quotes_excluded_tape_incomplete,
            "markets": self.markets,
            "event_days": self.event_days,
            "distinct_dates": self.distinct_dates,
            "independence_note": (
                f"{self.event_days} event-days across {self.distinct_dates} calendar "
                "date(s). Events recorded in one session are not independent draws in "
                "time; the interval resamples market-days and does not price the "
                "common-session factor"
            ),
            "markout_horizons_seconds": list(MARKOUT_HORIZONS),
            "estimators": {},
            "inadmissible": {
                FillEstimator.TOUCHED.value: (
                    "a print at the quoted price is not a fill; reported only so the "
                    "gap to the admissible estimators is visible"
                )
            },
            "not_measured": {
                "own_order_impact": (
                    "the quote was never sent, so nothing here captures how the book "
                    "would have reacted to it - other makers stepping in front, or "
                    "takers declining to cross a larger displayed size"
                ),
                "queue_cancellations": (
                    "the queue ahead is treated as static. Cancellations ahead of the "
                    "quote would move it up and raise the true fill rate, so the "
                    "queue model understates fills - the conservative direction, but "
                    "it is an approximation and not a measurement"
                ),
                "partial_fill_timing": (
                    "a fill is priced from the first moment the queue clears; a fill "
                    "that accumulated over the quote's life is marked from that first "
                    "moment rather than from each contract's own timestamp"
                ),
                "settlement_holding": (
                    "every number here assumes the position is marked or flattened "
                    "inside five minutes. Holding to settlement is a different "
                    "strategy with a different risk and is not measured"
                ),
            },
        }
        for estimator in FillEstimator:
            body["estimators"][estimator.value] = {
                "fills": self.fills(estimator),
                "fill_rate": str(round(self.fill_rate(estimator), 4)),
                "completion_rate": str(round(self.completion_rate(estimator), 4)),
                "mean_markout_given_fill": {
                    str(h): _s(self.mean_markout_given_fill(estimator, horizon=h))
                    for h in MARKOUT_HORIZONS
                },
                "mean_liquidation_given_fill": _s(
                    self.mean_liquidation_given_fill(estimator)
                ),
                "mean_hedge_cost_given_fill": _s(
                    self.mean_hedge_cost_given_fill(estimator)
                ),
                "hedge_availability": str(round(self.hedge_availability(estimator), 4)),
                "hedged_pair_pnl_per_contract": _s(self.hedged_pair_pnl(estimator)),
                "expectancy_per_quote_ci95": _ci(
                    self.cluster_bootstrap_ci(estimator, horizon=MARKOUT_HORIZONS[1])
                ),
                "unconditional_pnl_usd": {
                    str(h): str(self.unconditional_pnl(estimator, horizon=h))
                    for h in MARKOUT_HORIZONS
                },
                "expectancy_per_quote_usd": {
                    str(h): str(self.expectancy_per_quote(estimator, horizon=h))
                    for h in MARKOUT_HORIZONS
                },
                "admissible": estimator in ADMISSIBLE_ESTIMATORS,
            }
        return body


def _s(value: Decimal | None) -> str | None:
    return None if value is None else str(value)


def _ci(value: tuple[Decimal, Decimal] | None) -> list[str] | None:
    return None if value is None else [str(value[0]), str(value[1])]


def run_experiment(
    snapshots: Sequence[EventSnapshot],
    trades: Sequence[TradeRecord],
    policy: QuotePolicy,
    *,
    strategy_version: str,
    hedge_for: "Callable[[MakerQuote], tuple[str, Side] | None] | None" = None,
    tape_complete_through: datetime | None = None,
) -> MakerExperimentReport:
    """Place every quote the policy dictates and score all of them.

    ``hedge_for`` names the leg that closes a fill, when it is not simply the other
    side of the same book. On Kalshi it is: buying YES and buying NO in one market
    pays exactly $1. On Polymarket the two sides are separate tokens with separate
    books, so the closing leg is the *complement token*, and nothing in the quote
    itself says which one that is - the caller holds that mapping.
    """
    quotes = generate_quotes(snapshots, policy)
    excluded = 0
    if tape_complete_through is not None:
        #: A quote whose window runs past the point the tape is known complete cannot
        #: be scored: its fills may simply not have been indexed yet, and an unfilled
        #: quote scores exactly zero. Keeping it would book a missing print as a quote
        #: nobody traded against - a silent pull toward zero.
        kept = [q for q in quotes if q.expires_at <= tape_complete_through]
        excluded = len(quotes) - len(kept)
        quotes = kept
    index = ReplayIndex(trades, snapshots)
    outcomes = [
        evaluate_quote(
            q, trades, snapshots, policy=policy, index=index,
            hedge=hedge_for(q) if hedge_for else None,
        )
        for q in quotes
    ]
    event_days = {
        (q.event_ticker, q.placed_at.date().isoformat()) for q in quotes
    }
    return MakerExperimentReport(
        policy=policy,
        strategy_version=strategy_version,
        quotes_excluded_tape_incomplete=excluded,
        quotes_placed=len(quotes),
        markets=len({q.market for q in quotes}),
        event_days=len(event_days),
        distinct_dates=len({q.placed_at.date() for q in quotes}),
        outcomes=outcomes,
    )
