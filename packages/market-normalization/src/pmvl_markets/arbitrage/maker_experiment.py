"""Was the maker quote filled, and was being filled good news?

A resting order that is never filled earns nothing. That sentence is the whole design
constraint, and it is easy to violate by accident: quote a wide spread, observe that
the market traded at your price, and book the spread. Two things are wrong with that.
The trade at your price may have been somebody else's - you were behind them in the
queue - and if it *was* yours, you were filled because the other side wanted to trade
at that price, which is the moment the price is about to move against you.

So three separate numbers, none of which may stand in for the others:

``fill``
    Measured under three estimators that bracket the truth. ``TRADED_THROUGH`` is a
    lower bound: prints strictly past the quote prove the level was cleared. The
    ``QUEUE_MODEL`` central estimate assumes the quote joined *behind* everything
    already resting at its price. ``TOUCHED`` counts any print at the price as a full
    fill; it is computed only so that the gap between it and the others is visible,
    and it is never the basis of a verdict.
``markout``
    What the position was worth 30, 60 and 300 seconds later, from the recorded book -
    not from the price at which it was filled. A maker whose markout is negative is
    being adversely selected and the spread is not income, it is a payment for being
    wrong slightly later.
``unconditional expectancy``
    Total PnL over *every quote placed*, the unfilled ones contributing exactly zero.
    Dividing by fills instead of attempts is the arithmetic that makes every market
    making strategy look profitable.

Quotes are generated by a declared, mechanical policy over the whole recording. There
is no per-market selection, no skipping of quiet periods, and no discarding of a quote
because it went badly.
"""

