"""PIT collection hardening: source timing, station observations, poll telemetry

Three additions, each of which makes data permanently unusable if it is missing
at the moment of collection.

``source_observations`` gains source-to-market timing
    ``published_at`` and the poll interval. The source-lag hypothesis is a claim
    about the gap between a source publishing and a market moving; with only
    ``available_at`` the measurable quantity is the gap between OUR POLL and the
    market, which conflates a slow market with a slow collector. Those imply
    opposite trades. ``available_at`` remains the sole admissibility timestamp -
    these columns measure, they never gate.

``station_observations``
    Actual observed conditions at the settlement station, including the intraday
    path. Without them a study cannot separate forecast error from market lag,
    and a daily-maximum contract's mid-afternoon information advantage looks
    exactly like an alpha regime.

``poll_attempts``
    Every attempt, including failures. A missing observation and a missing
    collection are different facts; downtime is not missing-at-random.

Also ``markets.settlement_station_id``, kept apart from any forecast grid cell.

Every new timestamp is nullable and is stored NULL when the upstream product
does not provide one. None is defaulted to the collection time: a fabricated
publication timestamp reports zero lag for exactly the observations whose lag is
unknown.
"""

